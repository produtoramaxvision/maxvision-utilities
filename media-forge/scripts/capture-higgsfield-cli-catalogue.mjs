#!/usr/bin/env node
/**
 * Captures the `higgsfield` CLI catalogue into a versioned fixture.
 *
 * Every call this makes is a READ. `model list`, `workflow list` and
 * `generate cost` all answer without creating a job — the last one is the
 * platform's own pricing function, which is why the registry rates are measured
 * rather than transcribed from a marketing page. Running this spends 0 credits.
 *
 *   node scripts/capture-higgsfield-cli-catalogue.mjs
 *
 * Requires an authenticated CLI (`higgsfield auth login`). Writes
 * tests/fixtures/higgsfield-cli-catalogue.json.
 *
 * WHY A FIXTURE AT ALL
 *
 * The only thing proving the `higgsfield-cli` specs match the platform was the
 * live gate, which needs network and an OAuth session — neither of which CI has.
 * So a catalogue change (a model withdrawn, a price moved) was invisible until
 * someone happened to run the gate locally. The fixture splits that into two
 * failures that mean different things:
 *
 *   registry vs fixture   runs in CI, offline. Fails when the code drifts.
 *   fixture vs platform   live-gated. Fails when the PLATFORM drifts.
 *
 * Only the second one requires re-running this script.
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(HERE, '../tests/fixtures/higgsfield-cli-catalogue.json');
const BIN = process.env['MEDIA_FORGE_HF_BIN'] ?? 'higgsfield';

function hf(args) {
  const stdout = execFileSync(BIN, [...args, '--json'], {
    encoding: 'utf8',
    shell: process.platform === 'win32',
  });
  return JSON.parse(stdout);
}

/**
 * The cost grid, per job type.
 *
 * `resolutionFlag` mirrors `VideoModelSpec.cliResolutionParam`: kling3_0 has no
 * `resolution` param at all and answers `Unknown params: resolution` — its tiers
 * ride on `--mode std|pro|4k`. Capturing that here is the point; a grid that
 * assumed one flag shape would have silently skipped the model whose pricing is
 * least obvious.
 */
const GRID = [
  { jobType: 'kling3_0_turbo', durations: [5, 10], resolutions: ['720p', '1080p'] },
  {
    jobType: 'kling3_0',
    durations: [5, 10],
    resolutions: ['720p', '1080p', '4k'],
    resolutionFlag: { flag: '--mode', values: { '720p': 'std', '1080p': 'pro', '4k': '4k' } },
  },
  { jobType: 'seedance_2_0', durations: [5, 10], resolutions: ['480p', '720p', '1080p', '4k'] },
  { jobType: 'seedance_2_0_mini', durations: [5, 10], resolutions: ['480p', '720p'] },
  {
    jobType: 'cinematic_studio_video_3_5',
    durations: [5, 10, 15],
    resolutions: ['480p', '720p', '1080p'],
  },
  {
    jobType: 'marketing_studio_video',
    durations: [5, 10, 15],
    resolutions: ['480p', '720p', '1080p'],
  },
];

function costFor(entry, durationSec, resolution) {
  const args = ['generate', 'cost', entry.jobType, '--prompt', 'x', '--duration', String(durationSec)];
  if (entry.resolutionFlag) {
    const value = entry.resolutionFlag.values[resolution];
    if (value === undefined) return undefined;
    args.push(entry.resolutionFlag.flag, value);
  } else {
    args.push('--resolution', resolution);
  }
  try {
    const { credits } = hf(args);
    return typeof credits === 'number' ? credits : undefined;
  } catch {
    // A refusal is data: it means the platform does not price that combination.
    // Recorded as absent rather than guessed, so the fixture never claims a
    // shape the CLI rejects.
    return undefined;
  }
}

const videoModels = hf(['model', 'list', '--video']);
const imageModels = hf(['model', 'list', '--image']);
const workflows = hf(['workflow', 'list']);

const costs = {};
for (const entry of GRID) {
  const grid = {};
  for (const resolution of entry.resolutions) {
    for (const durationSec of entry.durations) {
      const credits = costFor(entry, durationSec, resolution);
      if (credits !== undefined) grid[`${resolution}@${durationSec}s`] = credits;
    }
  }
  costs[entry.jobType] = grid;
}

const fixture = {
  $comment:
    'GENERATED by scripts/capture-higgsfield-cli-catalogue.mjs. Do not hand-edit — re-run it. ' +
    'Every value is a CLI read; capturing this spends 0 credits.',
  capturedAt: new Date().toISOString().slice(0, 10),
  counts: {
    videoModels: videoModels.length,
    imageModels: imageModels.length,
    workflows: workflows.length,
  },
  videoModels: videoModels.map((m) => m.job_type).sort(),
  imageModels: imageModels.map((m) => m.job_type).sort(),
  workflows: workflows.map((w) => w.job_type).sort(),
  costs,
};

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, `${JSON.stringify(fixture, null, 2)}\n`, 'utf8');
console.log(
  `wrote ${OUT}\n  ${fixture.counts.videoModels} video, ${fixture.counts.imageModels} image, ` +
    `${fixture.counts.workflows} workflows, ${Object.keys(costs).length} priced job types`,
);
